// Build the client plugin bundle from the single-source stylesheet.
// DSH loads a client plugin as a browser script that registers itself on
// window.__ModuleLoader__ and returns { apply, inject }.

import fs from "node:fs";
import path from "node:path";

const here = import.meta.dirname;
const root = path.dirname(here);
const css = fs.readFileSync(path.join(root, "dsh-reasoning.css"), "utf-8");

const NAME = "dsh-reasoning-style";
const TAG = "dsh-reasoning-style/reasoning.css";

const client = `// Generated by build/gen.mjs from ../dsh-reasoning.css. Do not edit by hand.
window.__ModuleLoader__.load({
    id: ${JSON.stringify(NAME)},
    factory: (require) => {
        var module = { exports: {} };
        var exports = module.exports;
        Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });

        var CSS = ${JSON.stringify(css)};
        var TAG_ID = ${JSON.stringify(TAG)};

        function install() {
            if (typeof document === "undefined" || !document.head) return;
            if (document.querySelector('style[data-plugin-css="' + TAG_ID + '"]') !== null) return;
            var tag = document.createElement("style");
            tag.dataset.plugin = ${JSON.stringify(NAME)};
            tag.dataset.pluginCss = TAG_ID;
            tag.textContent = CSS;
            document.head.appendChild(tag);
        }

        // No client services are required: the plugin only adds a stylesheet.
        var inject = [];

        function apply(ctx) {
            install();
        }

        exports.apply = apply;
        exports.inject = inject;
        return module.exports;
    }
});
`;

const outDir = path.join(root, "plugin", "lib");
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "client.js"), client, "utf-8");
console.log("wrote", path.join(outDir, "client.js"), client.length, "bytes");
