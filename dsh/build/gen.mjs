// Build the client plugin bundle from the single-source stylesheet plus the
// table decoration parts. DSH loads a client plugin as a browser script that
// registers itself on window.__ModuleLoader__ and returns { apply, inject }.

import fs from "node:fs";
import path from "node:path";

const here = import.meta.dirname;
const root = path.dirname(here);
const css = fs.readFileSync(path.join(root, "onedark.css"), "utf-8");
const parts = JSON.parse(fs.readFileSync(path.join(here, "table-modes.json"), "utf-8"));

const NAME = "dsh-onedark";
const TAG = "dsh-onedark/onedark.css";
const TABLE_TAG = "dsh-onedark/table.css";
const BORDER_KEY = "onedark.tableBorder";
const STRIPE_KEY = "onedark.tableStripe";
const FLOW_KEY = "onedark.tableFlow";
const SIZE_KEY = "onedark.tableWidth";
const LEGACY_KEY = "onedark.tableStyle";

const client = `// Generated by build/gen.mjs from ../onedark.css and table-modes.json.
window.__ModuleLoader__.load({
    id: ${JSON.stringify(NAME)},
    factory: (require) => {
        var module = { exports: {} };
        var exports = module.exports;
        Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });

        var React = require("react");
        var h = React.createElement;
        var primitives = null;
        try {
            primitives = require("@deepseek-ai/dsh-client-ui-primitives");
        } catch (error) {
            primitives = null;
        }
        var Menu = primitives && primitives.Menu ? primitives.Menu : null;
        var Chevron = primitives && primitives.IconChevronDownOutlineRegular
            ? primitives.IconChevronDownOutlineRegular
            : null;

        var CSS = ${JSON.stringify(css)};
        var TAG_ID = ${JSON.stringify(TAG)};
        var PARTS = ${JSON.stringify(parts)};
        var TABLE_TAG_ID = ${JSON.stringify(TABLE_TAG)};
        var BORDER_KEY = ${JSON.stringify(BORDER_KEY)};
        var STRIPE_KEY = ${JSON.stringify(STRIPE_KEY)};
        var FLOW_KEY = ${JSON.stringify(FLOW_KEY)};
        var SIZE_KEY = ${JSON.stringify(SIZE_KEY)};
        var LEGACY_KEY = ${JSON.stringify(LEGACY_KEY)};
        var BORDERS = [
            ["grid", "全框线"],
            ["rows", "只留横线"],
            ["none", "无框线"],
        ];
        var STRIPES = [
            ["after", "表头后交替"],
            ["first", "从首行交替"],
            ["none", "不交替"],
        ];
        var FLOWS = [
            ["wrap", "折行"],
            ["scroll", "不折行"],
        ];
        var SIZES = [
            ["full", "填满正文"],
            ["content", "按内容"],
        ];
        var LEGACY = {
            github: ["grid", "after"],
            zebra: ["none", "first"],
            rules: ["rows", "none"],
            plain: ["none", "none"],
            off: ["off", "off"],
        };
        // Entries beginning with -- are read from the live tokens, so the swatch
        // can never drift from the stylesheet. The rest are syntax colours taken
        // from the theme's tokenColors, which are not part of the token system.
        var PALETTE = [
            ["底色", "--dsw-alias-bg-base"],
            ["面板", "--dsw-alias-bg-layer-2"],
            ["浮层", "--dsw-alias-bg-layer-4"],
            ["分隔线", "--dsw-alias-border-l2"],
            ["正文", "--dsw-alias-label-primary"],
            ["次要", "--dsw-alias-label-tertiary"],
            ["强调", "--dsw-alias-brand-primary"],
            ["链接", "--dsw-alias-brand-text"],
            ["字符串", "#98c379"],
            ["数字", "#d19a66"],
            ["关键字", "#c678dd"],
            ["注释", "#7f848e"],
        ];

        function resolveColor(source) {
            if (source.charAt(0) !== "-") return source;
            if (typeof document === "undefined" || !document.body) return source;
            var value = getComputedStyle(document.body).getPropertyValue(source);
            return value ? value.trim() : source;
        }

        function readSetting(key, allowed, fallback) {
            try {
                var stored = window.localStorage.getItem(key);
                if (stored !== null && allowed.indexOf(stored) >= 0) return stored;
            } catch (error) {
                // storage may be unavailable
            }
            return fallback;
        }

        function writeSetting(key, value) {
            try {
                window.localStorage.setItem(key, value);
            } catch (error) {
                // the choice stays for this session only
            }
        }

        // earlier builds stored one combined mode; map it onto the two axes
        function migrate() {
            try {
                var legacy = window.localStorage.getItem(LEGACY_KEY);
                if (legacy === null) return;
                var pair = LEGACY[legacy];
                if (pair) {
                    window.localStorage.setItem(BORDER_KEY, pair[0]);
                    window.localStorage.setItem(STRIPE_KEY, pair[1]);
                    window.localStorage.setItem(FLOW_KEY, "wrap");
                    window.localStorage.setItem(SIZE_KEY, "full");
                }
                window.localStorage.removeItem(LEGACY_KEY);
            } catch (error) {
                // ignore
            }
        }

        function readTable() {
            return {
                border: readSetting(BORDER_KEY, ["grid", "rows", "none", "off"], "grid"),
                stripe: readSetting(STRIPE_KEY, ["after", "first", "none", "off"], "after"),
                flow: readSetting(FLOW_KEY, ["wrap", "scroll", "off"], "wrap"),
                size: readSetting(SIZE_KEY, ["full", "content", "off"], "full"),
            };
        }

        function tableCss(state) {
            if (state.border === "off" || state.stripe === "off") return "";
            return PARTS.base
                + (PARTS.sizes[state.size] || "")
                + (PARTS.flows[state.flow] || "")
                + (PARTS.borders[state.border] || "")
                + (PARTS.stripes[state.stripe] || "");
        }

        function ensureStyle(attribute, id, text) {
            if (typeof document === "undefined" || !document.head) return null;
            var selector = attribute === "plugin-css"
                ? 'style[data-plugin-css="' + id + '"]'
                : "style[data-" + attribute + "]";
            var tag = document.querySelector(selector);
            if (tag === null) {
                tag = document.createElement("style");
                tag.dataset.plugin = ${JSON.stringify(NAME)};
                tag.dataset[attribute.replace(/-([a-z])/g, function (m, c) { return c.toUpperCase(); })] = "";
                tag.dataset.pluginCss = id;
                document.head.appendChild(tag);
            }
            if (text !== undefined) tag.textContent = text;
            return tag;
        }

        function applyTable(state) {
            ensureStyle("onedark-table", TABLE_TAG_ID, tableCss(state));
        }

        // The app exposes its own Menu primitive; the trigger borrows the
        // surface the app gives its selectors. A native select keeps the row
        // usable if that primitive is missing.
        var ROW = {
            display: "flex",
            alignItems: "center",
            justifyContent: "space-between",
            gap: "24px",
            padding: "16px 0",
            borderBottom: "0.5px solid var(--dsw-alias-border-l2)",
        };
        var TEXT = { display: "flex", flexDirection: "column", gap: "4px", minWidth: "0" };
        var TITLE = { fontSize: "14px", lineHeight: "20px", color: "var(--dsw-alias-label-primary)" };
        var DESC = { fontSize: "12px", lineHeight: "18px", color: "var(--dsw-alias-label-tertiary)" };

        var SELECT = {
            height: "36px",
            minWidth: "148px",
            padding: "0 10px 0 14px",
            border: "1px solid var(--dsw-alias-border-l2)",
            borderRadius: "6px",
            background: "var(--dsw-alias-bg-module-platform)",
            color: "var(--dsw-alias-label-primary)",
            font: "inherit",
            fontSize: "14px",
            lineHeight: "20px",
            cursor: "pointer",
        };

        function labelOf(options, value) {
            for (var i = 0; i < options.length; i += 1) {
                if (options[i][0] === value) return options[i][1];
            }
            return value;
        }

        function Chooser(props) {
            var state = React.useState(false);
            var open = state[0];
            var setOpen = state[1];
            var current = labelOf(props.options, props.value);

            if (Menu === null) {
                return h(
                    "select",
                    {
                        value: props.value,
                        style: SELECT,
                        onChange: function (event) { props.onChange(event.target.value); },
                    },
                    props.options.map(function (option) {
                        return h("option", { key: option[0], value: option[0] }, option[1]);
                    }),
                );
            }

            return h(Menu, {
                open: open,
                onClose: function () { setOpen(false); },
                items: props.options.map(function (option) {
                    return { id: option[0], label: option[1] };
                }),
                selectedId: props.value,
                onSelect: function (id) {
                    setOpen(false);
                    if (id !== props.value) props.onChange(id);
                },
                align: "end",
                portal: true,
                anchor: h(
                    "button",
                    {
                        type: "button",
                        className: "dsh-od-chooser",
                        "aria-haspopup": "menu",
                        "aria-expanded": open,
                        onClick: function () { setOpen(!open); },
                    },
                    current,
                    Chevron === null ? null : h(Chevron, { className: "dsh-od-chevron" }),
                ),
            });
        }

        function SettingRow(props) {
            return h(
                "div",
                { style: ROW },
                h(
                    "div",
                    { style: TEXT },
                    h("div", { style: TITLE }, props.title),
                    h("div", { style: DESC }, props.description),
                ),
                h(Chooser, { value: props.value, options: props.options, onChange: props.onChange }),
            );
        }

        function PaletteSection() {
            var tableState = React.useState(readTable());
            var table = tableState[0];
            var setTable = tableState[1];

            function pick(axis, key) {
                return function (value) {
                    var next = Object.assign({}, table);
                    next[axis] = value;
                    setTable(next);
                    var key = axis === "border"
                        ? BORDER_KEY
                        : axis === "stripe"
                            ? STRIPE_KEY
                            : axis === "flow"
                                ? FLOW_KEY
                                : SIZE_KEY;
                    writeSetting(key, next[axis]);
                    applyTable(next);
                };
            }

            return h(
                "div",
                { style: { display: "flex", flexDirection: "column", width: "100%" } },
                h(
                    "div",
                    { style: { padding: "16px 0" } },
                    h("div", { style: { fontSize: "14px", lineHeight: "22px", color: "var(--dsw-alias-label-primary)" } }, "One Dark Pro Darker"),
                    h(
                        "div",
                        { style: { ...DESC, marginTop: "4px" } },
                        "来源 zhuangtongfa.material-theme 3.20.3，取自主题文件的 Darker 变体。",
                    ),
                    h(
                        "div",
                        { style: { display: "flex", flexWrap: "wrap", gap: "8px", marginTop: "12px" } },
                        PALETTE.map(function (entry) {
                            return h(
                                "div",
                                {
                                    key: entry[0],
                                    style: { display: "flex", alignItems: "center", gap: "6px", minWidth: "112px" },
                                },
                                h("span", {
                                    style: {
                                        width: "12px",
                                        height: "12px",
                                        borderRadius: "3px",
                                        border: "1px solid var(--dsw-alias-border-l2)",
                                        background: resolveColor(entry[1]),
                                        display: "inline-block",
                                    },
                                }),
                                h(
                                    "span",
                                    { style: { ...DESC, lineHeight: "18px" } },
                                    entry[0] + " " + resolveColor(entry[1]),
                                ),
                            );
                        }),
                    ),
                ),
                h(SettingRow, {
                    title: "表格边框",
                    description: "Markdown 表格的框线样式。",
                    value: table.border,
                    options: BORDERS,
                    onChange: pick("border"),
                }),
                h(SettingRow, {
                    title: "表格交替",
                    description: "隔行底色的起始行。",
                    value: table.stripe,
                    options: STRIPES,
                    onChange: pick("stripe"),
                }),
                h(SettingRow, {
                    title: "表格宽度",
                    description: "整表占满正文宽度，还是按内容收紧。",
                    value: table.size,
                    options: SIZES,
                    onChange: pick("size"),
                }),
                h(SettingRow, {
                    title: "单元格折行",
                    description: "内容过长时是否换行；不折行会让表格横向滚动。",
                    value: table.flow,
                    options: FLOWS,
                    onChange: pick("flow"),
                }),
            );
        }

        var inject = [];

        function apply(ctx) {
            migrate();
            ensureStyle("onedark-table", TABLE_TAG_ID);
            ensureStyle("plugin-css", TAG_ID, CSS);
            applyTable(readTable());

            ctx.inject(["slots"], function (scoped) {
                scoped.slots.inject("settings.section", function () {
                    return scoped.slots.register(
                        {
                            name: "settings.section",
                            id: "onedark-palette",
                            order: 60,
                            label: function () { return "配色方案"; },
                        },
                        PaletteSection,
                    );
                });
            });
        }

        exports.apply = apply;
        exports.inject = inject;
        return module.exports;
    }
});
`;

const outDir = path.join(root, "plugin", "lib");
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "client.js"), client, "utf-8");
console.log("wrote", path.join(outDir, "client.js"), client.length, "bytes");
