// Build the client plugin bundle from the single-source stylesheet plus the
// table decoration modes. DSH loads a client plugin as a browser script that
// registers itself on window.__ModuleLoader__ and returns { apply, inject }.

import fs from "node:fs";
import path from "node:path";

const here = import.meta.dirname;
const root = path.dirname(here);
const css = fs.readFileSync(path.join(root, "onedark.css"), "utf-8");
const modes = JSON.parse(fs.readFileSync(path.join(here, "table-modes.json"), "utf-8"));

const NAME = "dsh-onedark";
const TAG = "dsh-onedark/onedark.css";
const TABLE_TAG = "dsh-onedark/table.css";
const STORAGE_KEY = "onedark.tableStyle";
const DEFAULT_MODE = "github";

const client = `// Generated by build/gen.mjs from ../onedark.css and table-modes.json.
window.__ModuleLoader__.load({
    id: ${JSON.stringify(NAME)},
    factory: (require) => {
        var module = { exports: {} };
        var exports = module.exports;
        Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });

        var React = require("react");
        var h = React.createElement;

        var CSS = ${JSON.stringify(css)};
        var TAG_ID = ${JSON.stringify(TAG)};
        var MODES = ${JSON.stringify(modes)};
        var TABLE_TAG_ID = ${JSON.stringify(TABLE_TAG)};
        var STORAGE_KEY = ${JSON.stringify(STORAGE_KEY)};
        var DEFAULT_MODE = ${JSON.stringify(DEFAULT_MODE)};
        var OPTIONS = [
            ["github", "网格"],
            ["zebra", "隔行底色"],
            ["rules", "只留横线"],
            ["plain", "无框线"],
            ["off", "关闭"],
        ];

        function ensureStyle(attribute, id, text) {
            if (typeof document === "undefined" || !document.head) return null;
            var selector = attribute === "plugin-css"
                ? 'style[data-plugin-css="' + id + '"]'
                : "style[data-" + attribute + "]";
            var tag = document.querySelector(selector);
            if (tag === null) {
                tag = document.createElement("style");
                tag.dataset.plugin = ${JSON.stringify(NAME)};
                tag.dataset[attribute.replace(/-([a-z])/g, function (m, c) { return c.toUpperCase(); })] = "";
                tag.dataset.pluginCss = id;
                document.head.appendChild(tag);
            }
            if (text !== undefined) tag.textContent = text;
            return tag;
        }

        function readMode() {
            try {
                var stored = window.localStorage.getItem(STORAGE_KEY);
                if (stored !== null && Object.prototype.hasOwnProperty.call(MODES, stored)) return stored;
            } catch (error) {
                // storage may be unavailable; fall through to the default
            }
            return DEFAULT_MODE;
        }

        function writeMode(mode) {
            try {
                window.localStorage.setItem(STORAGE_KEY, mode);
            } catch (error) {
                // the choice stays for this session only
            }
        }

        function applyTable(mode) {
            ensureStyle("onedark-table", TABLE_TAG_ID, MODES[mode] || "");
        }

        var rowStyle = {
            display: "flex",
            alignItems: "center",
            justifyContent: "space-between",
            gap: "24px",
            padding: "16px 0",
            borderBottom: "0.5px solid var(--dsw-alias-border-l2)",
        };
        var textStyle = { display: "flex", flexDirection: "column", gap: "4px", minWidth: "0" };
        var titleStyle = {
            fontSize: "14px",
            lineHeight: "20px",
            color: "var(--dsw-alias-label-primary)",
        };
        var descStyle = {
            fontSize: "12px",
            lineHeight: "18px",
            color: "var(--dsw-alias-label-tertiary)",
        };
        var selectStyle = { minWidth: "160px" };

        function TableStyleRow() {
            var state = React.useState(readMode());
            var mode = state[0];
            var setMode = state[1];

            function change(event) {
                var next = event.target.value;
                setMode(next);
                writeMode(next);
                applyTable(next);
            }

            return h(
                "div",
                { style: rowStyle },
                h(
                    "div",
                    { style: textStyle },
                    h("div", { style: titleStyle }, "表格样式"),
                    h("div", { style: descStyle }, "Markdown 表格的边框、隔行底色与列宽。"),
                ),
                h(
                    "select",
                    { value: mode, onChange: change, style: selectStyle },
                    OPTIONS.map(function (option) {
                        return h("option", { key: option[0], value: option[0] }, option[1]);
                    }),
                ),
            );
        }

        // The stylesheet installs even without any service; the settings row is
        // registered once the slot service is available.
        var inject = [];

        function apply(ctx) {
            ensureStyle("onedark-table", TABLE_TAG_ID);
            ensureStyle("plugin-css", TAG_ID, CSS);
            applyTable(readMode());

            ctx.inject(["slots"], function (scoped) {
                scoped.slots.inject("settings.general.item", function () {
                    return scoped.slots.register(
                        { name: "settings.general.item", id: "onedark-table-style", order: 60 },
                        TableStyleRow,
                    );
                });
            });
        }

        exports.apply = apply;
        exports.inject = inject;
        return module.exports;
    }
});
`;

const outDir = path.join(root, "plugin", "lib");
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "client.js"), client, "utf-8");
console.log("wrote", path.join(outDir, "client.js"), client.length, "bytes");
